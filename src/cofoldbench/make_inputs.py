"""Write predictor inputs from ``targets.csv``.

* Boltz-2 YAML (``data/inputs/boltz/{id}.yaml``)::

      version: 1
      sequences:
        - protein: {id: A, sequence: ...}   # msa omitted -> generated by --use_msa_server
        - protein: {id: B, sequence: ...}

  Format per https://github.com/jwohlwend/boltz/blob/main/docs/prediction.md
  ("If --use_msa_server is set, the MSA is auto-generated (so msa can be omitted)").

* ColabFold multimer FASTA (``data/inputs/colabfold/{id}.fasta``)::

      >{id}
      SEQ_A:SEQ_B

  Chains joined with ':' as documented for colabfold_batch complexes.

Usage
-----
    python -m cofoldbench.make_inputs [--config config.yaml]
"""

from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

import yaml

from .config import load_config, resolve
from .download import load_targets

log = logging.getLogger("cofoldbench.inputs")


def boltz_yaml(pid: str, seq_a: str, seq_b: str) -> str:
    """Return the Boltz-2 YAML text for a two-chain protein complex."""
    doc = {
        "version": 1,
        "sequences": [
            {"protein": {"id": "A", "sequence": seq_a}},
            {"protein": {"id": "B", "sequence": seq_b}},
        ],
    }
    header = f"# {pid}: chain A = entity 1, chain B = entity 2. MSA from the ColabFold server (--use_msa_server).\n"
    return header + yaml.safe_dump(doc, sort_keys=False, width=10_000)


def colabfold_fasta(pid: str, seq_a: str, seq_b: str) -> str:
    """Return the ColabFold complex FASTA (sequences joined by ':')."""
    return f">{pid}\n{seq_a}:{seq_b}\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="config.yaml")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    cfg = load_config(args.config)
    df = load_targets(cfg)
    bdir, cdir = resolve(cfg, "boltz_inputs"), resolve(cfg, "colabfold_inputs")
    bdir.mkdir(parents=True, exist_ok=True)
    cdir.mkdir(parents=True, exist_ok=True)
    for _, row in df.iterrows():
        pid, a, b = row["pdb_id"], row["seq_a"], row["seq_b"]
        Path(bdir / f"{pid}.yaml").write_text(boltz_yaml(pid, a, b))
        Path(cdir / f"{pid}.fasta").write_text(colabfold_fasta(pid, a, b))
    log.info("wrote %d Boltz YAML -> %s and %d ColabFold FASTA -> %s", len(df), bdir, len(df), cdir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
